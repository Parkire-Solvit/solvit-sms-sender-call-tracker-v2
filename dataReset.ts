async function getTotals(db: Q, cfg: SectionConfig) {
  const jobs = await db.queryOne<{ total: unknown; open: unknown; max_id: unknown }>(
    `SELECT COUNT(*) AS total,
            SUM(CASE WHEN status = 'AMBER' THEN 1 ELSE 0 END) AS open,
            COALESCE(MAX(id), 0) AS max_id
     FROM ${cfg.jobs}`
  );
  const logs = await db.queryOne<{ c: unknown }>(`SELECT COUNT(*) AS c FROM ${cfg.logs}`);
  const phones = cfg.phones ? await db.queryOne<{ c: unknown }>(`SELECT COUNT(*) AS c FROM ${cfg.phones.table}`) : null;
  const total = n(jobs?.total);
  const open = n(jobs?.open);
  return {
    jobs: total,
    open,
    closed: total - open,
    logs: n(logs?.c),
    phones: phones ? n(phones.c) : 0,
    max_job_id: n(jobs?.max_id),
  };
}

async function getFingerprint(db: Q, cfg: SectionConfig): Promise<string> {
  const t = await getTotals(db, cfg);
  const lastImport = await db.queryOne<{ m: unknown }>(`SELECT COALESCE(MAX(id), 0) AS m FROM ${cfg.imports}`);
  return `${t.jobs}:${t.max_job_id}:${t.logs}:${n(lastImport?.m)}`;
}

interface LastUploadInfo {
  id: number;
  file_name: string | null;
  imported_at: string | null;
  created_count: number;
  closed_absent_count: number;
  worked_created_count: number;
  can_undo: boolean;
  reason: string | null;
}

const WORKED_SQL = (cfg: SectionConfig) =>
  `SELECT COUNT(*) AS c FROM ${cfg.jobs} j
   WHERE j.created_by_import_id = ?
     AND (j.status <> 'AMBER'
          OR EXISTS (SELECT 1 FROM ${cfg.logs} l WHERE l.${cfg.logJobCol} = j.id AND COALESCE(l.logged_by, '') <> 'System'))`;

async function getLastUpload(db: Q, cfg: SectionConfig): Promise<LastUploadInfo | null> {
  const row = await db.queryOne<{
    id: unknown;
    file_name: string | null;
    imported_at: unknown;
    new_records_count: unknown;
    auto_closed_absent_count: unknown;
  }>(
    `SELECT id, file_name, imported_at, new_records_count, auto_closed_absent_count
     FROM ${cfg.imports} WHERE reverted_at IS NULL ORDER BY id DESC LIMIT 1`
  );
  if (!row) return null;
  const id = n(row.id);
  const created = await db.queryOne<{ c: unknown }>(`SELECT COUNT(*) AS c FROM ${cfg.jobs} WHERE created_by_import_id = ?`, [id]);
  const closed = await db.queryOne<{ c: unknown }>(
    `SELECT COUNT(*) AS c FROM ${cfg.jobs} WHERE closed_by_import_id = ? AND status = 'GREEN' AND latest_outcome = ?`,
    [id, cfg.absentOutcome]
  );
  const worked = await db.queryOne<{ c: unknown }>(WORKED_SQL(cfg), [id]);
  const createdCount = n(created?.c);
  const closedCount = n(closed?.c);
  const canUndo = createdCount + closedCount > 0;
  let reason: string | null = null;
  if (!canUndo) {
    reason =
      n(row.new_records_count) + n(row.auto_closed_absent_count) > 0
        ? "This upload was made before undo tracking was added, so it cannot be undone."
        : "The last upload did not create or close any records, so there is nothing to undo.";
  }
  return {
    id,
    file_name: row.file_name ?? null,
    imported_at: row.imported_at === null || row.imported_at === undefined ? null : String(row.imported_at),
    created_count: createdCount,
    closed_absent_count: closedCount,
    worked_created_count: n(worked?.c),
    can_undo: canUndo,
    reason,
  };
}

export async function getDataResetPreview(db: DbAdapter, sectionRaw: unknown) {
  const cfg = parseResetSection(sectionRaw);
  const totals = await getTotals(db, cfg);
  const lastUpload = await getLastUpload(db, cfg);
  return {
    section: cfg.id,
    label: cfg.label,
    reset_key_configured: isResetKeyConfigured(),
    delete_all_phrase: cfg.deleteAllPhrase,
    undo_phrase: UNDO_PHRASE,
    totals: { jobs: totals.jobs, open: totals.open, closed: totals.closed, logs: totals.logs, phones: totals.phones },
    last_upload: lastUpload,
  };
}

