function cleanCell(v: unknown): unknown {
  if (v === null || v === undefined) return null;
  if (v instanceof Date) return v.toISOString();
  if (typeof v === "bigint") return Number(v);
  if (typeof v === "string" && v.length > 32000) return v.slice(0, 32000);
  return v;
}

function toRows(rows: Array<Record<string, unknown>>): Array<Record<string, unknown>> {
  if (rows.length === 0) return [{ note: "No rows" }];
  return rows.map((r) => {
    const o: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(r)) o[k] = cleanCell(v);
    return o;
  });
}

export async function buildDataBackup(db: DbAdapter, sectionRaw: unknown, nowMs: number = Date.now()) {
  const cfg = parseResetSection(sectionRaw);
  const fingerprint = await getFingerprint(db, cfg);
  const totals = await getTotals(db, cfg);

  const wb = XLSX.utils.book_new();
  const jobs = await db.queryAll<Record<string, unknown>>(`SELECT * FROM ${cfg.jobs} ORDER BY id ASC`);
  const logs = await db.queryAll<Record<string, unknown>>(`SELECT * FROM ${cfg.logs} ORDER BY id ASC`);
  const imports = await db.queryAll<Record<string, unknown>>(`SELECT * FROM ${cfg.imports} ORDER BY id ASC`);
  XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(toRows(jobs)), "Records");
  XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(toRows(logs)), "Outcome history");
  if (cfg.phones) {
    const phones = await db.queryAll<Record<string, unknown>>(`SELECT * FROM ${cfg.phones.table} ORDER BY id ASC`);
    XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(toRows(phones)), "Phone numbers");
  }
  XLSX.utils.book_append_sheet(wb, XLSX.utils.json_to_sheet(toRows(imports)), "Uploads");
  XLSX.utils.book_append_sheet(
    wb,
    XLSX.utils.json_to_sheet([
      { item: "Section", value: cfg.label },
      { item: "Created at (UTC)", value: new Date(nowMs).toISOString() },
      { item: "Records", value: totals.jobs },
      { item: "Open records", value: totals.open },
      { item: "Closed records", value: totals.closed },
      { item: "Outcome history rows", value: totals.logs },
    ]),
    "About"
  );

  const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
  const stamp = new Date(nowMs).toISOString().slice(0, 19).replace(/[:T]/g, "-");
  return {
    buffer,
    filename: `${cfg.id}-backup-${stamp}.xlsx`,
    token: issueBackupToken(cfg.id, fingerprint, nowMs),
    counts: { jobs: totals.jobs, logs: totals.logs },
  };
}

