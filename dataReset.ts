// Delete all records
// ---------------------------------------------------------------------------

export interface DeleteAllBody {
  reset_key?: unknown;
  confirm_phrase?: unknown;
  confirm_count?: unknown;
  backup_token?: unknown;
}

export function deleteAllRecords(db: DbAdapter, sectionRaw: unknown, body: DeleteAllBody, nowMs: number = Date.now()) {
  const cfg = parseResetSection(sectionRaw);
  return exclusive(async () => {
    verifyResetKey(body?.reset_key, nowMs);
    if (str(body?.confirm_phrase) !== cfg.deleteAllPhrase) {
      throw new HttpError(400, `Type exactly: ${cfg.deleteAllPhrase}`);
    }
    const totals = await getTotals(db, cfg);
    if (totals.jobs === 0) throw new HttpError(409, "There are no records to delete.");
    if (str(body?.confirm_count) !== String(totals.jobs)) {
      throw new HttpError(400, `Type the exact number of records (${totals.jobs}) to confirm.`);
    }
    consumeBackupToken(str(body?.backup_token), cfg.id, await getFingerprint(db, cfg), nowMs);

    const result = { deleted_records: 0, deleted_history_rows: 0, deleted_phone_rows: 0 };
    await db.transaction(async (tx) => {
      const before = await getTotals(tx, cfg);
      result.deleted_records = before.jobs;
      result.deleted_history_rows = before.logs;
      result.deleted_phone_rows = before.phones;
      await tx.execute(`DELETE FROM ${cfg.logs}`);
      if (cfg.phones) await tx.execute(`DELETE FROM ${cfg.phones.table}`);
      await tx.execute(`DELETE FROM ${cfg.jobs}`);
      await tx.execute(`UPDATE ${cfg.imports} SET reverted_at = CURRENT_TIMESTAMP WHERE reverted_at IS NULL`);
      await tx.execute(
        `INSERT INTO settings_change_log (setting_key, old_value, new_value, changed_by) VALUES (?, ?, ?, ?)`,
        [`${cfg.settingKey}.delete_all`, `${before.jobs} records`, "0 records", "Admin (reset key)"]
      );
    });
    return { success: true, ...result };
  });
}

