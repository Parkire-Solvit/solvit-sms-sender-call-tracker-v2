// V18 dataReset.ts
// Danger zone for Callbacks and Pending Submissions: delete all records, or undo the last upload.
// Protected by a server-side reset key (DATA_RESET_KEY), typed confirmations and a mandatory backup.
// Never touches the Android call and SMS events, agents, settings, upload history rows or the other section.
import crypto from "node:crypto";
import * as XLSX from "xlsx";
import { DbAdapter, DbTransactionClient } from "./db";
import { HttpError } from "./httpError";

type Q = DbTransactionClient;

export type ResetSectionId = "callbacks" | "pending-submissions";

interface SectionConfig {
  id: ResetSectionId;
  label: string;
  deleteAllPhrase: string;
  jobs: string;
  logs: string;
  logJobCol: string;
  phones: { table: string; jobCol: string } | null;
  imports: string;
  settingKey: string;
  absentOutcome: string;
}

export const UNDO_PHRASE = "REMOVE LAST UPLOAD";

const CONFIGS: Record<ResetSectionId, SectionConfig> = {
  callbacks: {
    id: "callbacks",
    label: "Callbacks",
    deleteAllPhrase: "DELETE ALL CALLBACKS",
    jobs: "callback_jobs",
    logs: "callback_job_logs",
    logJobCol: "callback_job_id",
    phones: { table: "callback_job_phones", jobCol: "callback_job_id" },
    imports: "callback_imports",
    settingKey: "data_reset.callbacks",
    absentOutcome: "ABSENT_FROM_LATEST_EXPORT",
  },
  "pending-submissions": {
    id: "pending-submissions",
    label: "Pending Submissions",
    deleteAllPhrase: "DELETE ALL PENDING SUBMISSIONS",
    jobs: "pending_submission_jobs",
    logs: "pending_submission_logs",
    logJobCol: "pending_submission_job_id",
    phones: null,
    imports: "pending_submission_imports",
    settingKey: "data_reset.pending_submissions",
    absentOutcome: "ABSENT_FROM_LATEST_EXPORT",
  },
};

export function parseResetSection(raw: unknown): SectionConfig {
  const cfg = typeof raw === "string" ? (CONFIGS as Record<string, SectionConfig | undefined>)[raw] : undefined;
  if (!cfg) throw new HttpError(404, "Unknown section.");
  return cfg;
}

const str = (v: unknown): string => (typeof v === "string" ? v.trim() : "");
const n = (v: unknown): number => {
  const x = Number(v);
  return Number.isFinite(x) ? x : 0;
};

// ---------------------------------------------------------------------------
// Reset key (server side). The key is never returned by any endpoint.
// ---------------------------------------------------------------------------

const MIN_KEY_LENGTH = 12;
const MAX_FAILURES = 5;
const FAILURE_WINDOW_MS = 15 * 60 * 1000;
const LOCK_MS = 15 * 60 * 1000;

let failureTimes: number[] = [];
let lockedUntilMs = 0;

export function resetThrottleForTests(): void {
  failureTimes = [];
  lockedUntilMs = 0;
}

function configuredKey(): string {
  return (process.env.DATA_RESET_KEY || "").trim();
}

export function isResetKeyConfigured(): boolean {
  return configuredKey().length >= MIN_KEY_LENGTH;
}

function sameSecret(a: string, b: string): boolean {
  const ha = crypto.createHash("sha256").update(a).digest();
  const hb = crypto.createHash("sha256").update(b).digest();
  return crypto.timingSafeEqual(ha, hb);
}

/** Throws unless the reset key is configured on the server and the provided key matches. */
export function verifyResetKey(provided: unknown, nowMs: number = Date.now()): void {
  if (!isResetKeyConfigured()) {
    throw new HttpError(
      403,
      `Data reset is switched off. Set DATA_RESET_KEY (at least ${MIN_KEY_LENGTH} characters) on the server to enable it.`
    );
  }
  if (nowMs < lockedUntilMs) {
    const minutes = Math.max(1, Math.ceil((lockedUntilMs - nowMs) / 60000));
    throw new HttpError(429, `Too many incorrect reset keys. Try again in about ${minutes} minute(s).`);
  }
  const given = typeof provided === "string" ? provided : "";
  if (given.length > 0 && sameSecret(given, configuredKey())) {
    failureTimes = [];
    return;
  }
  failureTimes = failureTimes.filter((t) => nowMs - t < FAILURE_WINDOW_MS);
  failureTimes.push(nowMs);
  if (failureTimes.length >= MAX_FAILURES) {
    lockedUntilMs = nowMs + LOCK_MS;
    failureTimes = [];
  }
  throw new HttpError(403, "The reset key is incorrect.");
}

// ---------------------------------------------------------------------------
// Backup tokens: proof that a backup of the CURRENT data was generated by the server
// ---------------------------------------------------------------------------

const TOKEN_TTL_MS = 20 * 60 * 1000;
const MAX_TOKENS = 50;
const tokens = new Map<string, { section: ResetSectionId; fingerprint: string; expiresAt: number }>();

export function issueBackupToken(section: ResetSectionId, fingerprint: string, nowMs: number = Date.now()): string {
  for (const [k, v] of tokens) if (v.expiresAt <= nowMs) tokens.delete(k);
  while (tokens.size >= MAX_TOKENS) {
    const oldest = tokens.keys().next().value as string | undefined;
    if (oldest === undefined) break;
    tokens.delete(oldest);
  }
  const token = crypto.randomBytes(24).toString("hex");
  tokens.set(token, { section, fingerprint, expiresAt: nowMs + TOKEN_TTL_MS });
  return token;
}

/** Single use. Throws 409 when the backup is missing, expired, for another section, or the data changed since. */
export function consumeBackupToken(token: string, section: ResetSectionId, fingerprint: string, nowMs: number = Date.now()): void {
  const entry = token ? tokens.get(token) : undefined;
  if (token) tokens.delete(token);
  if (!entry || entry.expiresAt <= nowMs || entry.section !== section || entry.fingerprint !== fingerprint) {
    throw new HttpError(409, "A backup of the current data is required. Download a new backup and try again.");
  }
}

// ---------------------------------------------------------------------------
// Serialisation: one destructive operation at a time inside this process
// ---------------------------------------------------------------------------

let opChain: Promise<unknown> = Promise.resolve();
function exclusive<T>(fn: () => Promise<T>): Promise<T> {
  const run = opChain.then(fn, fn);
  opChain = run.catch(() => undefined);
  return run;
}

