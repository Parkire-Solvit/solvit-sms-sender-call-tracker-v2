// Undo last upload
// ---------------------------------------------------------------------------

export interface UndoBody {
  reset_key?: unknown;
  confirm_phrase?: unknown;
  backup_token?: unknown;
  allow_worked?: unknown;
}

export function undoLastUpload(db: DbAdapter, sectionRaw: unknown, body: UndoBody, nowMs: number = Date.now()) {
  const cfg = parseResetSection(sectionRaw);
  return exclusive(async () => {
    verifyResetKey(body?.reset_key, nowMs);
    if (str(body?.confirm_phrase) !== UNDO_PHRASE) throw new HttpError(400, `Type exactly: ${UNDO_PHRASE}`);

    const last = await getLastUpload(db, cfg);
    if (!last) throw new HttpError(409, "There is no upload to undo.");
    if (!last.can_undo) throw new HttpError(409, last.reason || "This upload cannot be undone.");
    if (last.worked_created_count > 0 && body?.allow_worked !== true) {
      throw new HttpError(
        409,
        `${last.worked_created_count} record(s) created by this upload have already been worked. Confirm that they may be deleted too.`,
        { worked_count: last.worked_created_count }
      );
    }
    consumeBackupToken(str(body?.backup_token), cfg.id, await getFingerprint(db, cfg), nowMs);

    const result = { removed_records: 0, restored_records: 0, upload_id: last.id, file_name: last.file_name };
    await db.transaction(async (tx) => {
      // 1. Reopen the records this upload closed because they were absent from the sheet.
      const absentLogs = await tx.queryAll<{ job_id: unknown; log_id: unknown }>(
        `SELECT l.${cfg.logJobCol} AS job_id, MAX(l.id) AS log_id
         FROM ${cfg.logs} l
         WHERE l.outcome = ?
           AND l.${cfg.logJobCol} IN (
             SELECT id FROM ${cfg.jobs}
             WHERE closed_by_import_id = ? AND status = 'GREEN' AND latest_outcome = ?)
         GROUP BY l.${cfg.logJobCol}`,
        [cfg.absentOutcome, last.id, cfg.absentOutcome]
      );
      const logByJob = new Map<number, number>(absentLogs.map((r) => [n(r.job_id), n(r.log_id)]));
      const toRestore = await tx.queryAll<{ id: unknown }>(
        `SELECT id FROM ${cfg.jobs} WHERE closed_by_import_id = ? AND status = 'GREEN' AND latest_outcome = ?`,
        [last.id, cfg.absentOutcome]
      );
      for (const r of toRestore) {
        const jobId = n(r.id);
        const logId = logByJob.get(jobId);
        if (logId !== undefined) await tx.execute(`DELETE FROM ${cfg.logs} WHERE id = ?`, [logId]);
        const previous = await tx.queryOne<{ outcome: string | null }>(
          `SELECT outcome FROM ${cfg.logs} WHERE ${cfg.logJobCol} = ? ORDER BY id DESC LIMIT 1`,
          [jobId]
        );
        const upd = await tx.execute(
          `UPDATE ${cfg.jobs}
           SET status = 'AMBER', closed_at = NULL, latest_outcome = ?, closed_by_import_id = NULL, updated_at = CURRENT_TIMESTAMP
           WHERE id = ? AND status = 'GREEN'`,
          [previous?.outcome ?? null, jobId]
        );
        if (upd.affectedRows === 1) result.restored_records += 1;
      }

      // 2. Delete the records this upload created, with their history and phone numbers.
      const createdCount = await tx.queryOne<{ c: unknown }>(`SELECT COUNT(*) AS c FROM ${cfg.jobs} WHERE created_by_import_id = ?`, [last.id]);
      result.removed_records = n(createdCount?.c);
      await tx.execute(
        `DELETE FROM ${cfg.logs} WHERE ${cfg.logJobCol} IN (SELECT id FROM ${cfg.jobs} WHERE created_by_import_id = ?)`,
        [last.id]
      );
      if (cfg.phones) {
        await tx.execute(
          `DELETE FROM ${cfg.phones.table} WHERE ${cfg.phones.jobCol} IN (SELECT id FROM ${cfg.jobs} WHERE created_by_import_id = ?)`,
          [last.id]
        );
      }
      await tx.execute(`DELETE FROM ${cfg.jobs} WHERE created_by_import_id = ?`, [last.id]);

      // 3. Keep the upload row for history, flagged as reverted.
      await tx.execute(`UPDATE ${cfg.imports} SET reverted_at = CURRENT_TIMESTAMP WHERE id = ?`, [last.id]);
      await tx.execute(
        `INSERT INTO settings_change_log (setting_key, old_value, new_value, changed_by) VALUES (?, ?, ?, ?)`,
        [
          `${cfg.settingKey}.undo_last_upload`,
          `upload ${last.id} (${last.file_name ?? "unknown file"})`,
          `removed ${result.removed_records}, restored ${result.restored_records}`,
          "Admin (reset key)",
        ]
      );
    });
    return { success: true, ...result };
  });
}
