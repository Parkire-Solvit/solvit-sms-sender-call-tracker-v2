/** Records which upload created and which upload closed (as absent) each listed record. */
export async function markImportRecords(
  q: Q,
  sectionId: ResetSectionId,
  importId: number,
  createdIds: number[],
  closedIds: number[]
): Promise<void> {
  if (!Number.isFinite(importId) || importId <= 0) return;
  const cfg = CONFIGS[sectionId];
  const chunk = <T,>(arr: T[], size: number): T[][] => {
    const out: T[][] = [];
    for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
    return out;
  };
  for (const ids of chunk(createdIds, 400)) {
    await q.execute(
      `UPDATE ${cfg.jobs} SET created_by_import_id = ? WHERE id IN (${ids.map(() => "?").join(",")})`,
      [importId, ...ids]
    );
  }
  for (const ids of chunk(closedIds, 400)) {
    await q.execute(
      `UPDATE ${cfg.jobs} SET closed_by_import_id = ? WHERE id IN (${ids.map(() => "?").join(",")})`,
      [importId, ...ids]
    );
  }
}
